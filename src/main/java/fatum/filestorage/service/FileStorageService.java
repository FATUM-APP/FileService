package fatum.filestorage.service;

import fatum.filestorage.configuration.StorageProperties;
import fatum.filestorage.dto.FileUploadResponse;
import fatum.filestorage.dto.PresignedUrlResponse;
import fatum.filestorage.exception.FileStorageException;
import fatum.filestorage.exception.StorageError;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;
import software.amazon.awssdk.core.exception.SdkException;
import software.amazon.awssdk.core.sync.RequestBody;
import software.amazon.awssdk.services.s3.S3Client;
import software.amazon.awssdk.services.s3.model.DeleteObjectRequest;
import software.amazon.awssdk.services.s3.model.GetObjectRequest;
import software.amazon.awssdk.services.s3.model.PutObjectRequest;
import software.amazon.awssdk.services.s3.model.PutObjectResponse;
import software.amazon.awssdk.services.s3.presigner.S3Presigner;
import software.amazon.awssdk.services.s3.presigner.model.GetObjectPresignRequest;

import java.io.IOException;
import java.io.InputStream;
import java.net.URLConnection;
import java.time.Duration;
import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Upload, delete and pre-sign operations shared by every microservice.
 *
 * <p>Files are stored under a key generated by this service, so callers can simply keep the returned
 * identifier. Validation (content type, size, name) is applied per route, which means a route can be
 * locked down to images while another one accepts PDFs.</p>
 */
@Service
public class FileStorageService {

    private static final Logger log = LoggerFactory.getLogger(FileStorageService.class);
    private static final String DEFAULT_CONTENT_TYPE = "application/octet-stream";

    private final S3Client s3Client;
    private final S3Presigner s3Presigner;
    private final StorageRouteResolver routeResolver;
    private final ObjectKeyFactory keyFactory;
    private final StorageProperties properties;

    public FileStorageService(
            S3Client s3Client,
            S3Presigner s3Presigner,
            StorageRouteResolver routeResolver,
            ObjectKeyFactory keyFactory,
            StorageProperties properties) {
        this.s3Client = s3Client;
        this.s3Presigner = s3Presigner;
        this.routeResolver = routeResolver;
        this.keyFactory = keyFactory;
        this.properties = properties;
    }

    /**
     * Stores a file in the bucket of the requested route.
     *
     * @param file      uploaded content; must be non empty and satisfy the route restrictions
     * @param routeName route such as {@code user-service:document}
     * @return the generated identifier, the object key and the stored metadata
     */
    public FileUploadResponse upload(MultipartFile file, String routeName) {
        ResolvedRoute route = routeResolver.resolve(routeName);
        validateFile(file, route);

        String safeFilename = keyFactory.sanitizeFilename(file.getOriginalFilename());
        String contentType = resolveContentType(file.getContentType(), safeFilename);
        ObjectKeyFactory.GeneratedKey generated = keyFactory.create(route.prefix(), safeFilename);

        Map<String, String> metadata = new LinkedHashMap<>();
        if (route.properties().getMetadata() != null) {
            metadata.putAll(route.properties().getMetadata());
        }
        metadata.put("route", route.name());
        metadata.put("original-filename", safeFilename);

        PutObjectRequest request = PutObjectRequest.builder()
                .bucket(route.bucket())
                .key(generated.key())
                .contentType(contentType)
                .contentLength(file.getSize())
                .metadata(metadata)
                .build();

        try (InputStream input = file.getInputStream()) {
            PutObjectResponse response = s3Client.putObject(request, RequestBody.fromInputStream(input, file.getSize()));
            log.info("Stored object route={} bucket={} key={} size={}",
                    route.name(), route.bucket(), generated.key(), file.getSize());
            return new FileUploadResponse(
                    generated.id(),
                    generated.key(),
                    route.bucket(),
                    route.name(),
                    safeFilename,
                    contentType,
                    file.getSize(),
                    response.eTag(),
                    Instant.now());
        } catch (SdkException | IOException exception) {
            log.error("Upload failed for route {} and key {}", route.name(), generated.key(), exception);
            throw new FileStorageException(StorageError.STORAGE_UNAVAILABLE, exception);
        }
    }

    /**
     * Removes an object. Deleting is idempotent: removing an object that no longer exists succeeds, so
     * callers can retry safely.
     */
    public void delete(String routeName, String objectKey) {
        ResolvedRoute route = routeResolver.resolve(routeName);
        requireOwnedKey(route, objectKey);
        try {
            s3Client.deleteObject(DeleteObjectRequest.builder()
                    .bucket(route.bucket())
                    .key(objectKey)
                    .build());
            log.info("Deleted object route={} bucket={} key={}", route.name(), route.bucket(), objectKey);
        } catch (SdkException exception) {
            log.error("Delete failed for route {} and key {}", route.name(), objectKey, exception);
            throw new FileStorageException(StorageError.STORAGE_UNAVAILABLE, exception);
        }
    }

    /** Builds a temporary download URL for an object of the route. */
    public PresignedUrlResponse presignedUrl(String routeName, String objectKey) {
        ResolvedRoute route = routeResolver.resolve(routeName);
        requireOwnedKey(route, objectKey);
        Duration ttl = routeResolver.presignTtl(route);
        try {
            GetObjectPresignRequest presignRequest = GetObjectPresignRequest.builder()
                    .signatureDuration(ttl)
                    .getObjectRequest(GetObjectRequest.builder()
                            .bucket(route.bucket())
                            .key(objectKey)
                            .build())
                    .build();
            String url = s3Presigner.presignGetObject(presignRequest).url().toString();
            return new PresignedUrlResponse(objectKey, route.bucket(), route.name(), url, Instant.now().plus(ttl));
        } catch (SdkException exception) {
            log.error("Presign failed for route {} and key {}", route.name(), objectKey, exception);
            throw new FileStorageException(StorageError.STORAGE_UNAVAILABLE, exception);
        }
    }

    private void validateFile(MultipartFile file, ResolvedRoute route) {
        if (file == null || file.isEmpty() || file.getSize() <= 0) {
            throw new FileStorageException(StorageError.EMPTY_FILE);
        }
        long maxSize = route.maxSizeBytes();
        if (maxSize > 0 && file.getSize() > maxSize) {
            throw new FileStorageException(
                    StorageError.FILE_TOO_LARGE,
                    List.of("Maximum size for route " + route.name() + " is " + maxSize + " bytes"));
        }
        String contentType = resolveContentType(file.getContentType(), file.getOriginalFilename());
        if (!isAllowed(contentType, route.allowedContentTypes())) {
            throw new FileStorageException(
                    StorageError.CONTENT_TYPE_NOT_ALLOWED,
                    List.of("Allowed content types: " + String.join(", ", route.allowedContentTypes())));
        }
    }

    private void requireOwnedKey(ResolvedRoute route, String objectKey) {
        if (objectKey == null || objectKey.isBlank()) {
            throw new FileStorageException(StorageError.OBJECT_KEY_REQUIRED);
        }
        if (!route.owns(objectKey)) {
            throw new FileStorageException(
                    StorageError.OBJECT_KEY_OUT_OF_ROUTE,
                    List.of("Route " + route.name() + " only manages keys under " + route.prefix() + "/"));
        }
    }

    /** Falls back to the extension when the client does not send a content type. */
    private String resolveContentType(String declaredContentType, String filename) {
        String normalized = keyFactory.normalizeContentType(declaredContentType);
        if (normalized == null || DEFAULT_CONTENT_TYPE.equals(normalized)) {
            String guessed = filename == null ? null : URLConnection.guessContentTypeFromName(filename);
            return guessed == null ? DEFAULT_CONTENT_TYPE : guessed;
        }
        return normalized;
    }

    /** Accepts exact types and family wildcards such as {@code image/*}. */
    private boolean isAllowed(String contentType, List<String> allowed) {
        if (allowed == null || allowed.isEmpty()) {
            return true;
        }
        return allowed.stream().anyMatch(candidate -> {
            String normalizedCandidate = keyFactory.normalizeContentType(candidate);
            if (normalizedCandidate == null) {
                return false;
            }
            if (normalizedCandidate.endsWith("/*")) {
                String family = normalizedCandidate.substring(0, normalizedCandidate.length() - 1);
                return contentType != null && contentType.startsWith(family);
            }
            return normalizedCandidate.equals(contentType);
        });
    }

    /** Exposes the global configuration to the controllers without leaking the properties object. */
    public Duration globalPresignTtl() {
        return properties.getPresignTtl();
    }
}
